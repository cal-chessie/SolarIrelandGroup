#!/usr/bin/env node
/**
 * Builds src/components/intake/analyser-door.css from intake.css.
 *
 * Why (13 Nov 2026, mobile LCP pass): the Bill Analyser sits under the home
 * hero, so its island wakes during the first load and pulled in all of
 * intake.css (64 KB raw, the whole intake app). PageSpeed flagged 86% of it
 * as unused. The analyser's resting state (the "door") now loads only the
 * rules that can match it; BillAnalyser loads the full intake.css the moment
 * the visitor reaches for it (pointer, key, focus, drag) and before any phase
 * change.
 *
 * Cascade invariant: every rule here is copied verbatim and in the original
 * order. When intake.css lands after it, each copy is matched by its own
 * original with the same specificity and a later position, so the copies can
 * never win and the page renders exactly as intake.css alone. The test
 * src/__tests__/analyser-door-css.test.ts guards that invariant.
 *
 * Selection: a rule is kept when, for at least one selector in its list,
 * every class it names appears in the prerendered HTML of the pages that
 * render the analyser (/, /solar-calculator) or in the floating widgets the
 * bottom-layer rules coordinate with. Attributes and pseudo-classes are
 * ignored, so hover, focus and data-state variants of door elements stay in.
 * Keyframes are kept when a kept rule names them.
 *
 * Run after `bun run build` whenever intake.css changes:
 *   node scripts/gen-analyser-door-css.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(root, 'src/components/intake/intake.css');
const OUT = path.join(root, 'src/components/intake/analyser-door.css');
const PAGES = ['.next/server/app/index.html', '.next/server/app/solar-calculator.html'];
// Mounted after hydration, outside the analyser, and named by the analyser's
// bottom-layer rules (chat bee, sticky CTA, cookie banner).
const WIDGETS = [
  'src/components/solar/WhatsAppChat.tsx',
  'src/components/solar/MobileStickyCTA.tsx',
  'src/components/CookieConsent.tsx',
];

const tokens = new Set();
for (const p of PAGES) {
  const file = path.join(root, p);
  if (!fs.existsSync(file)) {
    console.error(`Missing ${p}. Run \`bun run build\` first.`);
    process.exit(1);
  }
  const html = fs.readFileSync(file, 'utf8');
  for (const m of html.matchAll(/class="([^"]*)"/g)) for (const t of m[1].split(/\s+/)) if (t) tokens.add(t);
}
for (const w of WIDGETS) {
  const src = fs.readFileSync(path.join(root, w), 'utf8');
  for (const m of src.matchAll(/[\w-]+/g)) tokens.add(m[0]);
}

const classesOf = (selector) =>
  [...selector.replace(/\[[^\]]*\]/g, '').matchAll(/\.((?:\\.|[\w-])+)/g)].map((m) => m[1].replace(/\\(.)/g, '$1'));
const keep = (rule) => rule.selectors.some((sel) => classesOf(sel).every((c) => tokens.has(c)));

const css = fs.readFileSync(SRC, 'utf8');
const tree = postcss.parse(css, { from: SRC });

tree.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
  if (!keep(rule)) rule.remove();
});

const animNames = new Set();
tree.walkDecls(/^animation(-name)?$/, (d) => {
  for (const w of d.value.split(/[\s,]+/)) animNames.add(w);
});
tree.walkAtRules(/keyframes$/i, (at) => {
  if (!animNames.has(at.params.trim())) at.remove();
});

// Drop at-rules left empty, then comments that no longer introduce a rule.
let changed = true;
while (changed) {
  changed = false;
  tree.walkAtRules((at) => {
    if (at.nodes && !at.nodes.some((n) => n.type !== 'comment')) {
      at.remove();
      changed = true;
    }
  });
}
tree.walkComments((c) => {
  let n = c.next();
  while (n && n.type === 'comment') n = n.next();
  if (!n) c.remove();
});
// The source file's banner comment describes intake.css; ours replaces it.
if (tree.first?.type === 'comment') tree.first.remove();

const banner = `/* GENERATED by scripts/gen-analyser-door-css.mjs from intake.css. Do not edit.
   The Bill Analyser's resting state ("door"): the intake.css rules that can
   match it, verbatim and in order. BillAnalyser loads the full intake.css on
   the first pointer, key, focus or drag, and before any phase change. */
`;
const out = banner + tree.toString().replace(/^\s+/, '\n').replace(/\n{3,}/g, '\n\n');
fs.writeFileSync(OUT, out);
process.stdout.write(`analyser-door.css: ${out.length} bytes (intake.css ${css.length})\n`);
